"""How planning time and quality scale with network load.

    python -m benchmark.scaling                    # 3k-40k shipments x 3 seeds -> results/SCALING.md
    python -m benchmark.scaling --sizes 3000 6000 --seeds 1-2

For each size it times the stages an operator waits for after a re-plan
(detection, option generation, CP-SAT), records whether CP-SAT proved
optimality within its limit, and compares its objective with greedy's.
Runs sequentially with CP-SAT's default 8 workers, like the API does.
"""

from __future__ import annotations

import argparse
import csv
import statistics
import time
from pathlib import Path

from detection import OperatorView, detect
from detection.detector import KIND_AT_RISK
from recovery import Network, generate_options, leg_capacity
from recovery.optimizer import solve_cpsat, solve_greedy
from simulator import generate_scenario

from .run import RESULTS_DIR, _parse_seeds

SIZES = (3_000, 6_000, 10_000, 20_000, 40_000)
FIELDS = ("n_shipments", "seed", "flagged", "options", "contested_legs", "generate_s", "detect_s", "options_s",
          "cpsat_s", "cpsat_status", "optimality_gap_pct", "cpsat_objective", "greedy_s", "greedy_objective",
          "gap_pct")


def measure(n: int, seed: int, tightness: float, time_limit_s: float) -> dict:
    t = time.perf_counter()
    sc = generate_scenario(seed=seed, n_shipments=n, capacity_tightness=tightness)
    gen_s = time.perf_counter() - t
    view = OperatorView.from_scenario(sc)

    t = time.perf_counter()
    dets = [d for d in detect(view) if d.kind != KIND_AT_RISK]
    det_s = time.perf_counter() - t

    t = time.perf_counter()
    opts = generate_options(view, dets, network=Network(view))
    opt_s = time.perf_counter() - t

    cap = leg_capacity(view)
    cp = solve_cpsat(opts, cap, time_limit_s=time_limit_s)
    gr = solve_greedy(opts, cap)
    gap = 100 * (gr.objective_inr - cp.objective_inr) / cp.objective_inr if cp.objective_inr else 0.0
    return {
        "n_shipments": n, "seed": seed, "flagged": len(dets), "options": sum(map(len, opts.values())),
        "contested_legs": cp.stats.get("contested_legs", 0),
        "generate_s": round(gen_s, 2), "detect_s": round(det_s, 3), "options_s": round(opt_s, 3),
        "cpsat_s": cp.solve_s, "cpsat_status": cp.status, "optimality_gap_pct": cp.stats.get("gap_pct", 0.0),
        "cpsat_objective": round(cp.objective_inr),
        "greedy_s": gr.solve_s, "greedy_objective": round(gr.objective_inr),
        "gap_pct": round(gap, 2),
    }


def write_report(rows: list[dict], out: Path, tightness: float, time_limit_s: float) -> Path:
    sizes = sorted({r["n_shipments"] for r in rows})
    lines = [
        "# Piggyback scaling",
        "",
        f"Planning time and quality as the network gets busier (capacity tightness {tightness}, CP-SAT limit "
        f"{time_limit_s:.0f} s, 8 workers, one machine). Generated by `python -m benchmark.scaling`; means over "
        f"{len({r['seed'] for r in rows})} seeds.",
        "",
        "Plan time is what an operator waits for after pressing re-plan: detection, option generation and CP-SAT. "
        "It excludes generating the synthetic scenario.",
        "",
        "| Shipments | Stranded parcels | Options | Contested legs | Detect (s) | Options (s) | CP-SAT (s) "
        "| Plan time (s) | Proven optimal | Max gap to optimum | Greedy's extra cost |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for n in sizes:
        rs = [r for r in rows if r["n_shipments"] == n]
        m = lambda k: statistics.fmean(float(r[k]) for r in rs)  # noqa: E731
        optimal = sum(r["cpsat_status"] == "OPTIMAL" for r in rs)
        lines.append(
            f"| {n:,} | {m('flagged'):.0f} | {m('options'):,.0f} | {m('contested_legs'):.0f} | {m('detect_s'):.2f} "
            f"| {m('options_s'):.2f} | {m('cpsat_s'):.2f} | {m('detect_s') + m('options_s') + m('cpsat_s'):.2f} "
            f"| {optimal}/{len(rs)} | {max(float(r['optimality_gap_pct']) for r in rs):.2f}% | {m('gap_pct'):+.1f}% |")
    lines += [
        "",
        "Greedy's extra cost is how much higher greedy's objective (money + priority-weighted lateness) is than "
        "CP-SAT's on the same options, so it shows what the optimizer is worth as contention grows.",
        "",
        "Max gap to optimum comes from CP-SAT's lower bound: the plan is at most this far from the best possible "
        "plan (worst seed).",
        "",
    ]
    out.write_text("\n".join(lines), encoding="utf-8")
    return out


def main(argv: list[str] | None = None) -> Path:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--sizes", type=int, nargs="+", default=list(SIZES))
    ap.add_argument("--seeds", type=_parse_seeds, default=[1, 2, 3])
    ap.add_argument("--tightness", type=float, default=0.9)
    ap.add_argument("--time-limit", type=float, default=30.0)
    ap.add_argument("--out", type=Path, default=RESULTS_DIR / "scaling.csv")
    a = ap.parse_args(argv)

    rows = []
    for n in a.sizes:
        for seed in a.seeds:
            r = measure(n, seed, a.tightness, a.time_limit)
            rows.append(r)
            print(f"{n:>6} seed {seed}: {r['flagged']} stranded, {r['options']} options, plan "
                  f"{r['detect_s'] + r['options_s'] + r['cpsat_s']:.2f} s ({r['cpsat_status']}), "
                  f"greedy +{r['gap_pct']}%", flush=True)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    with open(a.out, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    report = write_report(rows, a.out.with_name("SCALING.md"), a.tightness, a.time_limit)
    print(f"wrote {a.out} and {report}")
    return report


if __name__ == "__main__":
    main()
